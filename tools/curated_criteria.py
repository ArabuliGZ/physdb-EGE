"""Compact, source-checked descriptions of the sample variants' rubrics.

These are deliberately labelled summaries. The complete official wording is
available in the downloadable original variant.
"""


def qualitative(laws: str) -> str:
    return f"""Краткое изложение критериев; полный текст — в исходном варианте.

3 балла. Правильный ответ и полное объяснение с указанием необходимых явлений и законов: {laws}.

2 балла. Правильный ответ и объяснение с одним из допустимых недочётов: не указан или не использован один необходимый закон или факт; есть один логический недочёт; присутствует неотделённая лишняя запись; есть одна неточность в описании закона или явления.

1 балл. Правильный ответ с существенно неполным объяснением либо верно названные законы и явления без доведённого до конца или безошибочного вывода.

0 баллов. Остальные случаи."""


def calculation(points: int, laws: str, drawing: str = "") -> str:
    elements = f"Физические законы: {laws}. "
    if drawing:
        elements += f"Рисунок: {drawing}. "
    elements += "Пояснение новых обозначений, необходимые преобразования и расчёты, правильный ответ"
    return f"""Краткое изложение критериев; полный текст — в исходном варианте.

{points} балла. Полное решение. {elements}.

{points - 1} балл{'а' if points - 1 > 1 else ''}. Законы записаны верно, преобразования направлены на решение, но есть один или несколько допустимых недостатков: неполный рисунок или пояснения, лишние записи, ошибка или пропуск в расчёте, неточный ответ.

{('1 балл. Частично верная запись необходимых законов или преобразований, не доведённая до верного ответа.\n\n') if points == 3 else ''}0 баллов. Остальные случаи."""


def justified(laws: str, drawing: str) -> str:
    return f"""Краткое изложение критериев; полный текст — в исходном варианте.

Критерий 1 — обоснование применимости законов (1 балл).
1 балл. Верно обоснованы необходимые модель и законы: {laws}.
0 баллов. Обоснование неполно, ошибочно или отсутствует.

Критерий 2 — решение (3 балла).
3 балла. Записаны необходимые законы, выполнен рисунок ({drawing}), пояснены обозначения, проведены преобразования и расчёты, дан правильный ответ.
2 балла. Законы и ход решения верны, но имеются допустимые недостатки рисунка, пояснений, преобразований или ответа.
1 балл. Представлена часть верного решения, но его недостаточно для оценки в 2 или 3 балла.
0 баллов. Остальные случаи.

Максимум: 4 балла."""


