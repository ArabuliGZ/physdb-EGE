def run(con: sqlite3.Connection, *, write: bool = False) -> dict[str, int]:
    source = ARCHIVE / "variant_3_fizika-ege-2024-0205_solutions.pdf"
    if not source.is_file():
        raise FileNotFoundError(source)
    rows = list(con.execute("""SELECT p.id,p.problem_number,p.answer,p.solution,p.criteria,p.review_notes
        FROM problems p JOIN variants v ON v.id=p.variant_id
        WHERE v.exam_year=2024 AND v.variant_number='БОТАЙ-ОСНОВ-1'
        AND p.problem_number BETWEEN 21 AND 26 AND p.alternative_number=1
        ORDER BY p.problem_number"""))
    if [r[1] for r in rows] != list(range(21, 27)):
        raise ValueError("Unexpected 2024 main variant 1 task set")
    counts = {field: 0 for field in ("answer", "solution", "criteria")}
    for pid, number, answer, solution, criteria, notes in rows:
        entry = DATA[number]
        manual_fields = edited_fields(pid)
        for field, current in (("answer", answer), ("solution", solution), ("criteria", criteria)):
            if field in manual_fields:
                continue
            owned = f"{field}: редакция ИИ по " in (notes or "")
            if current and not owned:
                continue
            counts[field] += 1
            if write:
                if owned:
                    con.execute(f"UPDATE problems SET {field}=? WHERE id=?", (entry[field], pid))
                    continue
                note = (f" {field}: редакция ИИ по {source.relative_to(ROOT).as_posix()}, "
                        f"PDF с. {entry['pages']}; требуется проверка.")
                con.execute(f"""UPDATE problems SET {field}=?,
                    review_notes=COALESCE(review_notes,'') || ?,extraction_status='needs_review'
                    WHERE id=? AND ({field} IS NULL OR trim({field})='')""",
                    (entry[field], note, pid))
    return counts


if __name__ == "__main__":
    with sqlite3.connect(DB) as connection:
        print(run(connection, write=True))
