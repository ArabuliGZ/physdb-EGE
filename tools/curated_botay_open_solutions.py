SOURCES = {(2025, "БОТАЙ-ОТКРЫТ-1"): 42649, (2026, "ОТКРЫТ-1"): 49641}
MARKER = "Решение ИИ по опубликованному разбору; требуется проверка."


def run(con: sqlite3.Connection, *, write: bool = False, year_filter: int | None = None) -> int:
    count = 0
    for (year, variant), tasks in SOLUTIONS.items():
        if year_filter is not None and year != year_filter:
            continue
        for number, body in tasks.items():
            row = con.execute("""SELECT p.id,p.solution,p.review_notes,p.answer
                FROM problems p JOIN variants v ON v.id=p.variant_id
                WHERE v.exam_year=? AND v.variant_number=? AND p.problem_number=?
                AND p.alternative_number=1""", (year, variant, number)).fetchone()
            if not row:
                raise ValueError(f"Missing {year}-{variant} #{number}")
            pid, current, notes, answer = row
            fields = edited_fields(pid)
            owned = "solution: редакция ИИ по" in (notes or "")
            if "solution" in fields or current and not owned:
                continue
            text = MARKER + "\n" + dedent(body).strip()
            count += 1
            if write:
                if owned:
                    con.execute("UPDATE problems SET solution=? WHERE id=?", (text, pid))
                else:
                    source_id = SOURCES[(year, variant)] + number - 21
                    note = (f" solution: редакция ИИ по https://phys-ege.sdamgia.ru/problem?id={source_id}; "
                            "формулы сверены с условием, требуется проверка.")
                    con.execute("""UPDATE problems SET solution=?,
                        review_notes=COALESCE(review_notes,'') || ?,extraction_status='needs_review'
                        WHERE id=? AND (solution IS NULL OR trim(solution)='')""", (text, note, pid))
            if year == 2025 and number == 26 and "answer" not in fields and answer == r"\(0{,}25\)" and \
                    "Ответ опубликован: https://phys-ege.sdamgia.ru/problem?id=42654" in (notes or ""):
                if write:
                    con.execute("""UPDATE problems SET answer=?,
                        review_notes=COALESCE(review_notes,'') || ? WHERE id=?""",
                        (r"\(0{,}35\)", " answer: расчёт ИИ для r=7 см в исходном PDF; требуется проверка.", pid))
    return count


if __name__ == "__main__":
    with sqlite3.connect(DB) as connection:
        print(f"Completed AI open-variant worked solutions: {run(connection, write=True)}")
