def rubric(points: int, number: int, laws: str) -> str:
    lead = "Критерии оценивания — редакция ИИ; требуется проверка по авторскому источнику."
    if number == 21:
        return "\n".join((
            lead,
            f"\\(3\\) балла: Дан верный вывод; все существенные этапы объяснены через {laws}; схема сил или график, если требуется, выполнены верно.",
            "\\(2\\) балла: Вывод верен и объяснение в целом правильно, но пропущен один необходимый физический довод или допущен один недочёт в схеме.",
            "\\(1\\) балл: Указан верный результат без достаточного объяснения либо приведены необходимые законы без полного вывода.",
            "\\(0\\) баллов: Нет верного результата и физически обоснованного объяснения.",
        ))
    rows = [lead]
    if points == 4:
        rows.extend((
            "\\(4\\) балла: Обоснована применимость физических законов; записана достаточная система уравнений; выполнены преобразования и получен верный ответ с единицей измерения.",
            "\\(3\\) балла: Обоснование и способ решения верны, но есть один недочёт в вычислении, обозначениях или записи ответа.",
            "\\(2\\) балла: Верно обоснована применимость законов и записана существенная часть системы уравнений, однако решение не доведено до ответа.",
            "\\(1\\) балл: Приведён один необходимый закон либо одна существенная верная связь между величинами.",
        ))
    elif points == 3:
        rows.extend((
            f"\\(3\\) балла: Верно применены {laws}; выполнены необходимые преобразования и расчёт; дан ответ с единицей измерения.",
            "\\(2\\) балла: Ход решения верен, но допущен один вычислительный недочёт либо неполно записан ответ.",
            "\\(1\\) балл: Записаны необходимые физические законы и часть уравнений, но полного решения нет.",
        ))
    elif points == 2:
        rows.extend((
            f"\\(2\\) балла: Верно применены {laws}; получен правильный ответ с единицей измерения.",
            "\\(1\\) балл: Физические законы выбраны верно, но есть ошибка в преобразовании или вычислении либо решение не завершено.",
        ))
    else:
        raise ValueError(points)
    rows.append("\\(0\\) баллов: Решение не соответствует условиям получения более высокого балла.")
    return "\n".join(rows)


def run(con: sqlite3.Connection, *, write: bool = False, year_filter: int | None = None) -> int:
    count = 0
    for (year, variant), steps in STEPS.items():
        if year_filter is not None and year_filter != year:
            continue
        for number, laws in zip(range(21, 27), steps):
            row = con.execute("""SELECT p.id,p.max_points,p.criteria,p.review_notes FROM problems p
                JOIN variants v ON v.id=p.variant_id WHERE v.exam_year=? AND
                v.variant_number=? AND p.problem_number=? AND p.alternative_number=1""",
                (year, variant, number)).fetchone()
            if not row:
                raise ValueError(f"Missing {year}-{variant} №{number}")
            pid, points, current, notes = row
            owned = "criteria: редакция ИИ; требуется проверка по авторскому источнику" in (notes or "")
            if current and current.strip() and not owned or "criteria" in edited_fields(pid):
                continue
            count += 1
            if write:
                if owned:
                    con.execute("UPDATE problems SET criteria=? WHERE id=?", (rubric(points, number, laws), pid))
                else:
                    con.execute("""UPDATE problems SET criteria=?,
                        review_notes=COALESCE(review_notes,'') || ?, extraction_status='needs_review'
                        WHERE id=? AND (criteria IS NULL OR trim(criteria)='')""",
                        (rubric(points, number, laws), " criteria: редакция ИИ; требуется проверка по авторскому источнику.", pid))
    return count


